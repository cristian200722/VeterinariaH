CREATE TABLE recuperacion_contrasena (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id BIGINT NOT NULL,
    codigo_hash VARCHAR(60) NOT NULL,
    creado_en TIMESTAMP NOT NULL,
    expira_en TIMESTAMP NOT NULL,
    intentos SMALLINT NOT NULL DEFAULT 0,
    usado BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_recuperacion_admin
        FOREIGN KEY (admin_id) REFERENCES admin(id) ON DELETE CASCADE,
    CONSTRAINT chk_recuperacion_intentos
        CHECK (intentos BETWEEN 0 AND 5)
);

CREATE INDEX idx_recuperacion_admin_creado
    ON recuperacion_contrasena (admin_id, creado_en DESC);
